#[test]
fn single_type_with_disconnected_methods_is_not_a_package_split() {
    let src = "package pkg\n\ntype Big struct{ a, b int }\nfunc (g *Big) A1() int { return g.a }\nfunc (g *Big) A2() int { return g.a + 1 }\nfunc (g *Big) B1() int { return g.b }\nfunc (g *Big) B2() int { return g.b + 1 }\n";
    let model = model_of("gpf-supernode", &[("pkg/big.go", src)]);
    assert!(run(&model, EvidenceMode::Combined).is_empty());
    assert!(run(&model, EvidenceMode::GraphOnly).is_empty());
}

#[test]
fn test_file_symbols_and_import_edges_are_excluded() {
    let test_src =
        "package pkg\n\ntype T1 struct{}\ntype T2 struct{}\ntype T3 struct{}\ntype T4 struct{}\n";
    let model = model_of("gpf-testfile", &[("pkg/a_test.go", test_src)]);
    assert!(run(&model, EvidenceMode::Combined).is_empty());

    let mut model = fixture_model("mixed_concerns");
    let pkg = model.packages.keys().next().unwrap().clone();
    model.import_edges.push(crate::import_graph::ImportEdge {
        from: pkg,
        to: "other".to_string(),
        file: PathBuf::from("mixed_concerns/x_test.go"),
        line: 3,
    });
    let reports = analyze(&model, EvidenceMode::Combined);
    assert_eq!(reports[0].coverage.test_import_edges_excluded, 1);
    assert!(reports[0].cycle_risks[0].contains("test-only cycles are not reported"));
}

#[test]
fn entry_point_package_is_informational() {
    let imports: String = (0..6)
        .map(|i| format!("import _ \"example.test/app/dep{i}\"\n"))
        .collect();
    let main_src = format!("package main\n\n{imports}\nfunc main() {{}}\n");
    let deps: Vec<(String, String)> = (0..6)
        .map(|i| (format!("dep{i}/d.go"), format!("package dep{i}\n")))
        .collect();
    let mut files: Vec<(&str, &str)> = vec![
        ("cmd/app/main.go", &main_src),
        ("cmd/app/a.go", MIXED_DECODE),
        ("cmd/app/b.go", MIXED_STORE),
    ];
    files.extend(deps.iter().map(|(p, s)| (p.as_str(), s.as_str())));
    let findings = run(&model_of("gpf-entry", &files), EvidenceMode::Combined);
    assert_eq!(findings.len(), 1, "{findings:?}");
    let first = findings[0].message.lines().next().unwrap();
    assert!(
        first.starts_with("[go-package-focus] [informational]"),
        "{first}"
    );
    assert!(!first.contains("(advisory)"), "{first}");
}

#[test]
fn size_only_mode_marks_large_package_informational_but_combined_stays_silent() {
    let files: Vec<(String, String)> = (0..SIZE_ONLY_MIN_FILES)
        .map(|i| {
            (
                format!("big/f{i}.go"),
                format!("package big\n\nfunc F{i}() {{}}\n"),
            )
        })
        .collect();
    let refs: Vec<(&str, &str)> = files
        .iter()
        .map(|(p, s)| (p.as_str(), s.as_str()))
        .collect();
    let model = model_of("gpf-size", &refs);
    let sized = run(&model, EvidenceMode::SizeOnly);
    assert_eq!(sized.len(), 1);
    assert!(
        sized[0]
            .message
            .starts_with("[go-package-focus] [informational]")
    );
    assert!(run(&model, EvidenceMode::Combined).is_empty());
}

