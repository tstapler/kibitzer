use super::*;
use crate::arch_model::{PruneConfig, build_model_from_files};
use std::path::PathBuf;

const MIXED_DECODE: &str = "package pkg\n\ntype Decoder struct{ pos int }\ntype Token struct{ kind string }\nfunc (d *Decoder) Next() int { d.pos++; return d.pos }\nfunc (t *Token) Kind() string { return t.kind }\nfunc ReadToken(d *Decoder, t *Token) string { d.Next(); return t.Kind() }\n";
const MIXED_STORE: &str = "package pkg\n\ntype Store struct{ rows []string }\ntype Record struct{ id string }\nfunc (s *Store) Put(r *Record) { s.rows = append(s.rows, r.ID()) }\nfunc (r *Record) ID() string { return r.id }\nfunc Save(s *Store, r *Record) { s.Put(r) }\n";

fn model_of(label: &str, files: &[(&str, &str)]) -> ArchModel {
    let dir = crate::test_support::unique_temp_dir(label);
    std::fs::write(dir.join("go.mod"), "module example.test/app\n\ngo 1.21\n").unwrap();
    let paths: Vec<PathBuf> = files
        .iter()
        .map(|(name, src)| {
            let path = dir.join(name);
            std::fs::create_dir_all(path.parent().unwrap()).unwrap();
            std::fs::write(&path, src).unwrap();
            path
        })
        .collect();
    build_model_from_files(
        &dir,
        &paths,
        &PruneConfig {
            include_private: true,
        },
    )
    .unwrap()
}

fn fixture_model(package: &str) -> ArchModel {
    let root = PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("testdata/dogfood-architecture");
    let paths: Vec<PathBuf> = std::fs::read_dir(root.join(package))
        .unwrap()
        .map(|e| e.unwrap().path())
        .filter(|p| p.extension().is_some_and(|e| e == "go"))
        .collect();
    build_model_from_files(
        &root,
        &paths,
        &PruneConfig {
            include_private: true,
        },
    )
    .unwrap()
}

fn run(model: &ArchModel, mode: EvidenceMode) -> Vec<ArchFinding> {
    GoPackageFocusChecker::new(mode).check(model, &ArchitectureConfig::default())
}

